def _investigation(ctx):
    inv = ctx.artifacts.get("mac_investigation")
    if not inv:
        return None
    return {k: inv.get(k) for k in ("mode", "days", "watch", "include_content", "access_problems", "databases",
                                     "questions")}


def tool_fingerprint() -> dict:
    """SHA-256 of every source/rule file of the running Aletheia build (proves which code produced the report)."""
    base = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    files = {}
    for root, _d, fs in os.walk(base):
        if "__pycache__" in root:
            continue
        for f in sorted(fs):
            if f.endswith((".py", ".yar", ".yara", ".txt")):
                full = os.path.join(root, f)
                files[os.path.relpath(full, base).replace(os.sep, "/")] = sha256_file(full)
    return {"name": TOOL_NAME, "version": __version__, "files": len(files),
            "build_sha256": sha256_bytes(canonical_json(files)), "file_hashes": files}


def verdict(findings: list) -> dict:
    counts = {s: 0 for s in SEV_ORDER}
    for f in findings:
        counts[f["severity"]] = counts.get(f["severity"], 0) + 1
    if counts["critical"]:
        v, txt = "COMPROMISE INDICATED", ("Critical indicators of compromise were identified. The device should be "
                                          "treated as compromised and contained.")
    elif counts["high"]:
        v, txt = "SUSPICIOUS - INVESTIGATION REQUIRED", ("High-severity suspicious activity was identified that "
                                                          "requires analyst validation.")
    elif counts["medium"]:
        v, txt = "ANOMALIES DETECTED", "Medium-severity anomalies were identified; review is recommended."
    else:
        v, txt = "NO INDICATORS OF COMPROMISE IDENTIFIED", ("No indicators of compromise were identified within the "
                                                            "documented scope and limitations. This is not proof "
                                                            "that the device is clean.")
    return {"verdict": v, "statement": txt, "counts": counts}


def timeline(ctx) -> list:
    ev = []
    sysinfo = ctx.artifacts.get("system") or {}
    if sysinfo.get("boot_time_utc"):
        ev.append({"time": sysinfo["boot_time_utc"], "source": "system", "event": "System boot"})
    for f in ctx.findings:
        if f.get("event_time_utc"):
            ev.append({"time": f["event_time_utc"], "source": f["rule_id"], "event": f["title"], "finding": f["id"],
                       "severity": f["severity"]})
    flagged = {ev.get("ref") for f in ctx.findings for ev in f.get("evidence", [])
               if str(ev.get("ref", "")).startswith("pid=")}
    for p in ctx.artifacts.get("processes", []):
        if p.get("start_time_utc") and f"pid={p.get('pid')}" in flagged:
            ev.append({"time": p["start_time_utc"], "source": "processes",
                       "event": f"Process start {p.get('name')} (PID {p.get('pid')})"})
    for e in (ctx.artifacts.get("logs") or {}).get("windows_events", [])[:2000]:
        if e.get("time_utc"):
            ev.append({"time": e["time_utc"], "source": e.get("log"), "event": f"Event {e.get('event_id')}"})
    inv = ctx.artifacts.get("mac_investigation") or {}
    for q in inv.get("questions", []):
        if q["id"] not in ("Q1", "Q7", "Q9"):
            continue
        for title, t in q.get("tables", {}).items():
            if "date" not in t["columns"]:
                continue
            i = t["columns"].index("date")
            for row in t["rows"][:500]:
                if row[i]:
                    ev.append({"time": row[i], "source": f"{q['id']} {title}",
                               "event": " | ".join(str(v) for j, v in enumerate(row) if j != i and v)[:200]})
    ev.sort(key=lambda x: str(x["time"]))
    return ev


def stix_bundle(ctx) -> dict:
    """STIX 2.1 bundle: identity, observed-data style indicators + sightings for matched IOCs."""
    now = utc_now()
    ident = f"identity--{uuid.uuid5(uuid.NAMESPACE_URL, 'aletheia:' + ctx.case.case_id)}"
    objs = [{"type": "identity", "spec_version": "2.1", "id": ident, "created": now, "modified": now,
             "name": ctx.case.organization or ctx.case.examiner, "identity_class": "organization"}]
    for f in ctx.findings:
        for ev in f.get("evidence", []):
            ioc = ev.get("ioc")
            if not ioc:
                continue
            t, v = ioc["type"], ioc["value"]
            pattern = {
                "sha256": f"[file:hashes.'SHA-256' = '{v}']", "sha1": f"[file:hashes.'SHA-1' = '{v}']",
                "md5": f"[file:hashes.MD5 = '{v}']", "ipv4": f"[ipv4-addr:value = '{v}']",
                "ipv6": f"[ipv6-addr:value = '{v}']", "domain": f"[domain-name:value = '{v}']",
                "url": f"[url:value = '{v}']", "filename": f"[file:name = '{v}']",
            }.get(t)
            if not pattern:
                continue
            ind_id = f"indicator--{uuid.uuid5(uuid.NAMESPACE_URL, pattern)}"
            if not any(o["id"] == ind_id for o in objs):
                objs.append({"type": "indicator", "spec_version": "2.1", "id": ind_id, "created": now, "modified": now,
                             "name": f"{t}: {v}", "description": ioc.get("threat") or ioc.get("description") or "",
                             "pattern": pattern, "pattern_type": "stix", "valid_from": now,
                             "indicator_types": ["malicious-activity"], "created_by_ref": ident})
            objs.append({"type": "sighting", "spec_version": "2.1", "id": f"sighting--{uuid.uuid4()}",
                         "created": now, "modified": now, "sighting_of_ref": ind_id, "count": 1,
                         "description": f"{f['id']} {f['title']} on host "
                                        f"{(ctx.artifacts.get('system') or {}).get('hostname')}",
                         "created_by_ref": ident})
    return {"type": "bundle", "id": f"bundle--{uuid.uuid4()}", "objects": objs}


def findings_csv(findings: list) -> str:
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(["id", "severity", "confidence", "rule_id", "category", "title", "attack_techniques", "event_time_utc",
                "evidence_refs", "recommendation"])
    for f in findings:
        w.writerow([f["id"], f["severity"], f["confidence"], f["rule_id"], f.get("category"), f["title"],
                    ";".join(a["id"] for a in f.get("attack", [])), f.get("event_time_utc") or "",
                    " | ".join(str(e.get("ref")) for e in f.get("evidence", [])), f.get("recommendation")])
    return buf.getvalue()


def timeline_csv(events: list) -> str:
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(["time_utc", "source", "event", "finding", "severity"])
    for e in events:
        w.writerow([e.get("time"), e.get("source"), e.get("event"), e.get("finding", ""), e.get("severity", "")])
    return buf.getvalue()


def investigation_csvs(ctx) -> dict:
    inv = ctx.artifacts.get("mac_investigation") or {}
    out = {}
    for q in inv.get("questions", []):
        for title, t in q.get("tables", {}).items():
            buf = io.StringIO()
            w = csv.writer(buf)
            w.writerow(t["columns"])
            for row in t["rows"]:
                w.writerow(["" if v is None else (", ".join(map(str, v)) if isinstance(v, list) else v) for v in row])
            out[f"{q['id']}_{title}"] = buf.getvalue()
    return out


def build_report_data(ctx, ioc_db, started: str, ended: str, plan: dict) -> dict:
    from aletheia import feeds

    return {
        "report_format": "aletheia-report/1.0",
        "generated_utc": utc_now(),
        "tool": {k: v for k, v in tool_fingerprint().items()},
        "case": ctx.case.__dict__,
        "acquisition": {"started_utc": started, "ended_utc": ended, "profile": ctx.profile,
                        "mode": "LIVE TRIAGE - read-only", "case_dir": ctx.case_dir},
        "host": ctx.artifacts.get("system"),
        "scope": ctx.artifacts.get("filesystem_scope"),
        "verdict": verdict(ctx.findings),
        "findings": ctx.findings,
        "intel": {"ioc_counts": ioc_db.stats(), "ioc_sources": ioc_db.sources, "feeds_snapshot": feeds.snapshot(),
                  "yara": (ctx.artifacts.get("yara") or {}).get("status")},
        "external_tools": ctx.artifacts.get("external_tools"),
        "commands_executed": ctx.runner.history,
        "evidence_index": list(ctx.store.index),
        "errors": ctx.errors,
        "remediation_plan": plan,
        "standards": STANDARDS,
        "legal_notes": LEGAL_NOTES,
        "nist_csf": NIST_CSF,
        "nist_ir_phase": NIST_IR_PHASE,
        "audit_chain_head": ctx.audit.head,
        "investigation": _investigation(ctx),
    }
